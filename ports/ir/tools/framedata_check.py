"""Compare a Geno LAB export with hitboxes compiled from an Ultimate ACMD dump.

    python ports/ir/tools/framedata_check.py
    python ports/ir/tools/framedata_check.py --self-test

Defaults target Sora (Ultimate fighter id ``trail``). Only common Attack* states are
converted by acmd_to_ftcmd. LAB input chains and Geno specials are listed as
unmapped; they are generated by different tools. LAB exports contain no hitbox
offsets, so expected offsets are retained in JSON but cannot be compared.
"""
