"""Writes moves/kame_{charge,tap,mid,full,super}.genoasm from the table below (KAMEHAMEHA.md has the same numbers and the reasons).

    python ports/goku-xv2/tools/gen_kame.py

Clip frames are the release row's frames (the script clock); ANIM_RATE < 1 stretches them, so the beam lasts `beam` GAME frames while the
pose barely moves. Hitbox offsets are in the right hand's frame along the measured beam direction D (kame_geom.py); the beam effect uses the same D.
Lengths and radii below are authored model units; the engine scales them by SCALE (1.43), world = 1.43 x authored.
"""
import math
from pathlib import Path

from kame_geom import D, SCALE

MOVES = Path(__file__).resolve().parents[1] / 'moves'

# tier: start = clip frame the beam leaves, beam = beam length in game frames, rate = ANIM_RATE during it, total = clip frames,
# size/ks = the four hit spheres (radius, distance along the beam), dmg/fkb/stun/rehit = the drag hits, fin = the launching final hit
TIERS = {
    # tier 0, fired before "ka": a quick ki blast, two short hits, tiny flinch
    'tap':   dict(start=5,  beam=8,  rate=0.6,  total=26, size=2.0, ks=(4, 8, 12, 16),        dmg=1.0, fkb=8, stun=4, rehit=5,
                  fin=dict(dmg=2, angle=55, kbg=40, bkb=20, size=2.4)),
    # tier 1, "ka": a short thin beam, a few weak hits, low knockback
    'thin':  dict(start=6,  beam=20, rate=0.5,  total=36, size=2.4, ks=(4.5, 10, 15.5, 21),   dmg=1.1, fkb=7, stun=5, rehit=5,
                  fin=dict(dmg=3, angle=55, kbg=50, bkb=25, size=2.8)),
    # tier 2, "me": a medium beam that drags
    'mid':   dict(start=6,  beam=28, rate=0.45, total=45, size=3.2, ks=(5.5, 12, 18.5, 25),   dmg=1.0, fkb=8, stun=6, rehit=5,
                  fin=dict(dmg=4, angle=45, kbg=80, bkb=35, size=3.6)),
    # tier 3, "ha": a long thick beam with a launching finisher
    'full':  dict(start=8,  beam=40, rate=0.4,  total=60, size=4.2, ks=(7, 15.5, 24, 32.5),   dmg=1.2, fkb=8, stun=6, rehit=5,
                  fin=dict(dmg=7, angle=40, kbg=90, bkb=50, size=4.8)),
    # tier 4, the full chant: the widest, longest beam, the strongest finisher, the biggest push back
    'max':   dict(start=10, beam=50, rate=0.35, total=75, size=5.4, ks=(9, 20, 31, 42),       dmg=1.3, fkb=8, stun=6, rehit=5,
                  fin=dict(dmg=10, angle=38, kbg=95, bkb=60, size=6.4)),
    'super': dict(start=54, beam=60, rate=0.15,  total=70, size=6.0, ks=(10, 22, 34, 46),      dmg=2.2, fkb=8, stun=6, rehit=5,
                  fin=dict(dmg=16, angle=40, kbg=80, bkb=60, size=7.0)),
}
HEAD = {
    'tap': 'Tap blast (tier 0, released before "ka")', 'thin': 'Thin beam (tier 1, "ka")', 'mid': 'Mid beam (tier 2, "me")', 'full': 'Full beam (tier 3, "ha")',
    'max': 'Max beam (tier 4, the full chant)', 'super': 'Super Kamehameha (full chant + ki 100)',
}


def spheres(t, ks, size, dmg, angle, kbg, fkb, bkb, shield=0):
    out = []
    for slot, k in enumerate(ks):
        out.append('hitbox slot=%d joint=@HAND_R@ damage=%g size=%g x=%.2f y=%.2f z=%.2f angle=%d kbg=%d fkb=%d bkb=%d element=2 shield=%d'
                   % (slot, dmg, size, k * D[0], k * D[1], k * D[2], angle, kbg, fkb, bkb, shield))
    return out


def tier(name):
    t = TIERS[name]
    bc = t['beam'] * t['rate']                # beam length in clip frames
    end = t['start'] + bc
    L = ['# Kamehameha %s. Generated by tools/gen_kame.py (numbers: KAMEHAMEHA.md). Destination design, no source script.' % HEAD[name],
         '# Beam = four spheres along the hands, built out over 3 clip frames, re-hitting every %d frames; the beam effect is fx P_TrailGokuKame%s.' % (t['rehit'], name.capitalize()),
         'PUT ANIM_RATE 1.0', 'clear_hitboxes',
         *(['sfx behavior=1 sfx_id=200103 volume=127 panning=64'] + sum([['wait_until %d' % f, 'sfx behavior=1 sfx_id=%d volume=127 panning=64' % i]
                                                                           for f, i in ((4, 200121), (18, 200124), (32, 200127), (44, 200130))], []) if name == 'super' else []),
         'wait_until %d' % t['start'],
         # XV2 BAC: the release shout (VOX cue 1) 2 frames after the projectile, the shot SE with it (tools/xv2_audio.py)
         'sfx behavior=1 sfx_id=%d volume=127 panning=64' % (200106 if name == 'super' else 200115),
         'sfx behavior=1 sfx_id=%d volume=127 panning=64' % (200109 if name == 'super' else 200118), 'PUT ANIM_RATE %g' % t['rate']]
    first = True
    for i, k in enumerate(t['ks']):
        L.append('hitbox slot=%d joint=@HAND_R@ damage=%g size=%g x=%.2f y=%.2f z=%.2f angle=361 kbg=60 fkb=%d bkb=0 element=2 shield=0'
                 % (i, t['dmg'], t['size'], k * D[0], k * D[1], k * D[2], t['fkb']))
        if first:
            L += ['REHIT 15 %d' % t['rehit'], 'HBSTUN 15 %d' % t['stun'], 'HBFLAGS 15 1']  # 1 = no hitlag: the beam keeps its rhythm
            first = False
        if i < 3:
            L.append('wait 1')
    # REHIT keeps running: its next clear frees the final hit's target (a victim in hitstun is still on the drag hits' list); the pose is
    # still held (rate r) for the final hit's 5 game frames, the clip speeds up only after it
    L += ['wait_until %g' % math.ceil(end), 'HBFLAGS 15 0', 'clear_hitboxes']
    f = t['fin']
    # the drag carries the victim down the beam (about 2 units a hit), so the final hit's spheres sit further out than the beam's
    L += spheres(name, tuple(k + 5 for k in t['ks']), f['size'], f['dmg'], f['angle'], f['kbg'], 0, f['bkb'])
    L += ['wait %d' % math.ceil(5 * t['rate']), 'REHIT 15 0', 'clear_hitboxes', 'PUT ANIM_RATE 1.0', 'wait_until %d' % t['total'], 'iasa']
    return '\n'.join(L) + '\n'


CHARGE = """# Kamehameha charge: B once, then it charges by itself (lua/goku.lua; the natives' model, KAMEHAMEHA.md section 0). Full is ~130 frames after B.
# Voice: XV2's chant "ka-me-ha-me" (VOX cue 0, cut into its four syllables, tools/xv2_audio.py) spread across the charge, one syllable per step;
# the "HA!" (cue 1) plays on release (the beam scripts). The charge SE (SE cue 0 = waveform 4_charge, 2.1 s) starts with the move. No damaging hitbox.
PUT ANIM_RATE 1.0
clear_hitboxes
sfx behavior=1 sfx_id=200100 volume=127 panning=64
wait_until 7
sfx behavior=1 sfx_id=200121 volume=127 panning=64
wait_until 44
sfx behavior=1 sfx_id=200124 volume=127 panning=64
wait_until 80
sfx behavior=1 sfx_id=200127 volume=127 panning=64
wait_until 114
sfx behavior=1 sfx_id=200130 volume=127 panning=64
wait_until 134
"""

if __name__ == '__main__':
    for n in TIERS:
        (MOVES / ('kame_%s.genoasm' % n)).write_text(tier(n), encoding='utf-8', newline='\n')
    (MOVES / 'kame_charge.genoasm').write_text(CHARGE, encoding='utf-8', newline='\n')
    print('wrote', len(TIERS) + 1, 'scripts to', MOVES)
