"""Writes moves/kame_{charge,tap,mid,full,super}.genoasm from the table below (KAMEHAMEHA.md has the same numbers and the reasons).

    python ports/goku-xv2/tools/gen_kame.py

Clip frames are the release row's frames (the script clock); ANIM_RATE < 1 stretches them, so the beam lasts `beam` GAME frames while the
pose barely moves. Hitbox offsets are in the right hand's frame along the measured beam direction D (kame_geom.py); the beam effect uses the same D.
Lengths and radii below are authored model units; the engine scales them by SCALE (1.43), world = 1.43 x authored.
"""
import math
from pathlib import Path

from kame_geom import D, SCALE

MOVES = Path(__file__).resolve().parents[1] / 'moves'

# tier: start = clip frame the beam leaves, beam = beam length in game frames, rate = ANIM_RATE during it, total = clip frames,
# size/ks = the four hit spheres (radius, distance along the beam), dmg/fkb/stun/rehit = the drag hits, fin = the launching final hit
TIERS = {
    'tap':   dict(start=5,  beam=14, rate=0.5,  total=30, size=2.4, ks=(4, 9.5, 15, 20.5),    dmg=1.2, fkb=10, stun=5, rehit=5,
                  fin=dict(dmg=3, angle=50, kbg=60, bkb=25, size=2.8)),
    'mid':   dict(start=6,  beam=28, rate=0.45, total=45, size=3.2, ks=(5.5, 12, 18.5, 25),   dmg=1.2, fkb=12, stun=6, rehit=5,
                  fin=dict(dmg=5, angle=45, kbg=80, bkb=35, size=3.6)),
    'full':  dict(start=8,  beam=46, rate=0.4,  total=60, size=4.2, ks=(7, 15.5, 24, 32.5),   dmg=1.5, fkb=14, stun=6, rehit=5,
                  fin=dict(dmg=10, angle=40, kbg=90, bkb=50, size=4.8)),
    'super': dict(start=30, beam=60, rate=0.4,  total=70, size=6.0, ks=(10, 22, 34, 46),      dmg=2.0, fkb=16, stun=6, rehit=5,
                  fin=dict(dmg=16, angle=40, kbg=80, bkb=60, size=7.0)),
}
HEAD = {
    'tap': 'Tap beam (charge < 15 frames)', 'mid': 'Mid beam (charge 15-44)', 'full': 'Full beam (charge 45-60)',
    'super': 'Super Kamehameha (full charge + ki 100)',
}


def spheres(t, ks, size, dmg, angle, kbg, fkb, bkb, shield=0):
    out = []
    for slot, k in enumerate(ks):
        out.append('hitbox slot=%d joint=@HAND_R@ damage=%g size=%g x=%.2f y=%.2f z=%.2f angle=%d kbg=%d fkb=%d bkb=%d element=2 shield=%d'
                   % (slot, dmg, size, k * D[0], k * D[1], k * D[2], angle, kbg, fkb, bkb, shield))
    return out


def tier(name):
    t = TIERS[name]
    bc = t['beam'] * t['rate']                # beam length in clip frames
    end = t['start'] + bc
    L = ['# Kamehameha %s. Generated by tools/gen_kame.py (numbers: KAMEHAMEHA.md). Destination design, no source script.' % HEAD[name],
         '# Beam = four spheres along the hands, built out over 3 clip frames, re-hitting every %d frames; the beam effect is fx P_TrailGokuKame%s.' % (t['rehit'], name.capitalize()),
         'PUT ANIM_RATE 1.0', 'clear_hitboxes',
         'wait_until %d' % t['start'], 'sfx behavior=1 sfx_id=164 volume=127 panning=64', 'PUT ANIM_RATE %g' % t['rate']]
    first = True
    for i, k in enumerate(t['ks']):
        L.append('hitbox slot=%d joint=@HAND_R@ damage=%g size=%g x=%.2f y=%.2f z=%.2f angle=361 kbg=0 fkb=%d bkb=0 element=2 shield=0'
                 % (i, t['dmg'], t['size'], k * D[0], k * D[1], k * D[2], t['fkb']))
        if first:
            L += ['REHIT 15 %d' % t['rehit'], 'HBSTUN 15 %d' % t['stun'], 'HBFLAGS 15 1']  # 1 = no hitlag: the beam keeps its rhythm
            first = False
        if i < 3:
            L.append('wait 1')
    L += ['wait_until %g' % math.ceil(end), 'REHIT 15 0', 'HBFLAGS 15 0', 'clear_hitboxes', 'PUT ANIM_RATE 1.0']
    f = t['fin']
    L += spheres(name, t['ks'], f['size'], f['dmg'], f['angle'], f['kbg'], 0, f['bkb'])
    L += ['wait 3', 'clear_hitboxes', 'wait_until %d' % t['total'], 'iasa']
    return '\n'.join(L) + '\n'


CHARGE = """# Kamehameha charge ("ka-me-ha-me"): hold B. Generated by tools/gen_kame.py. Lua counts the charge (lua/goku.lua: 15 frames a step,
# 60 = full, no auto-fire); the glowing ki ball between the hands is fx P_TrailGokuKameCharge (bound to this state, grows over the 60 frames
# and flashes at each step). No damaging hitbox. Step sounds on the 15-frame beat.
PUT ANIM_RATE 1.0
clear_hitboxes
wait_until 15
sfx behavior=1 sfx_id=164 volume=60 panning=64
wait_until 30
sfx behavior=1 sfx_id=164 volume=80 panning=64
wait_until 45
sfx behavior=1 sfx_id=164 volume=100 panning=64
wait_until 60
sfx behavior=1 sfx_id=164 volume=127 panning=64
wait_until 80
"""

if __name__ == '__main__':
    for n in TIERS:
        (MOVES / ('kame_%s.genoasm' % n)).write_text(tier(n), encoding='utf-8', newline='\n')
    (MOVES / 'kame_charge.genoasm').write_text(CHARGE, encoding='utf-8', newline='\n')
    print('wrote', len(TIERS) + 1, 'scripts to', MOVES)
